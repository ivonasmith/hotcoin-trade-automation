"""Daily poster facts: BTC leg (up-leg or down-leg) and the alt window day.

The BTC leg comes straight from the website's daily leg file (uncleonchain.com/data/leg_latest.json, generated by
leg/leg_data.py in the uncleonchain repo from closed Binance spot BTCUSDT daily candles). The trading plan does not keep
its own leg start any more: whatever the website shows (up-leg or down-leg, start, day, numbers) is what the plan uses.
The altcoin-wide leg (alt_leg) comes from the same file. The old alt-window D0 in poster/poster_state.json is still
read for backward compatibility, but the poster no longer shows the alt window (the website moved it to its detail page). Output: runtime/poster_facts.json (uploaded with the
snapshot). Never fails the workflow: on any problem it writes {"ok": false, "error": ...}.
"""
import json
import sys
import urllib.request
from datetime import date, datetime, timedelta, timezone
from pathlib import Path

HERE = Path(__file__).resolve().parent
STATE = HERE.parent / "poster" / "poster_state.json"
BEIJING = timezone(timedelta(hours=8))
MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"]
LEG_URLS = ["https://uncleonchain.com/data/leg_latest.json",
            "https://raw.githubusercontent.com/ivonasmith/uncleonchain/main/site/data/leg_latest.json"]
LEG_STALE_DAYS = 3   # 和网站一样：数据截至日比今天早 3 天以上算停更，不出读数


def utc_day(ts_ms):
    return datetime.fromtimestamp(ts_ms / 1000, timezone.utc).date()


def fetch_leg(urls=LEG_URLS):
    err = None
    for url in urls:
        try:
            req = urllib.request.Request(url + ("&" if "?" in url else "?") + "t=" + str(int(datetime.now().timestamp())),
                                         headers={"User-Agent": "hotcoin-desk/1.0"})
            with urllib.request.urlopen(req, timeout=20) as resp:
                return json.loads(resp.read().decode())
        except Exception as exc:  # noqa: BLE001
            err = exc
    raise ValueError(f"网站涨跌腿数据取不到：{err}")


def leg_facts(site, today):
    """把网站 leg_latest.json 的 btc_leg 原样转成海报 / 闸门用的字段。数字一个不重算，和网站完全一致。"""
    b = (site or {}).get("btc_leg") or {}
    L, d = b.get("leg") or {}, b.get("direction")
    if d not in ("up", "down") or not L:
        raise ValueError(f"网站涨跌腿数据没有方向（direction={d!r}）")
    asof = date.fromisoformat(site["asof"])
    if (today - asof).days > LEG_STALE_DAYS:
        raise ValueError(f"网站涨跌腿数据停更：截至 {asof}，比今天早 {(today - asof).days} 天")
    badge = b.get("badge") or {}
    out = {"dir": d, "day": L["day"], "start": L["start_date"], "start_close": L["start_close"], "confirm": L["confirm_date"],
           "asof": site["asof"], "badge_zh": badge.get("zh"), "badge_en": badge.get("en"), "prev": b.get("prev_leg")}
    if d == "up":
        hd = date.fromisoformat(L["high_date"])
        refreshed = L["high_date"] == site["asof"]
        out.update({"peak_pct": L["gain_pct"], "high_close": L["high_close"], "high_date": L["high_date"],
                    "peak_note_zh": f"{hd:%m-%d}最高收盘{L['high_close']:,.0f}，" + ("今日刷新" if refreshed else "未刷新"),
                    "peak_note_en": f"{MONTHS[hd.month - 1]} {hd.day} peak close {L['high_close']:,.0f}, " + ("new high" if refreshed else "not exceeded"),
                    "dd": L["max_dd_pct"], "dd_date": L["max_dd_date"][5:]})
    else:
        out.update({"drop_pct": L["drop_pct"], "low_close": L["low_close"], "low_date": L["low_date"], "btc_close": L["btc_close"],
                    "from_peak_pct": L["from_peak_pct"], "reversal_line": L["reversal_line"], "to_reversal_pct": L["to_reversal_pct"]})
    return out


def alt_leg_facts(site):
    """网站 leg_latest.json 的 alt_leg（山寨整体涨跌腿：币安成交额前 50 左右山寨币等权指数，15% 折线）。网站没生成时返回 None。
    和网站一样只给百分比，不给指数点位。"""
    a = (site or {}).get("alt_leg") or {}
    L, d = a.get("leg") or {}, a.get("direction")
    if d not in ("up", "down") or not L:
        return None
    basket = a.get("basket") or {}
    out = {"dir": d, "day": L["day"], "start": L["start_date"], "confirm": L["confirm_date"], "prev": a.get("prev_leg"),
           "coins": basket.get("coins_today"), "threshold_pct": basket.get("threshold_pct")}
    if d == "up":
        out.update({"gain_pct": L["gain_pct"], "max_dd_pct": L["max_dd_pct"]})
    else:
        out.update({"drop_pct": L["drop_pct"], "from_peak_pct": L["from_peak_pct"], "to_reversal_pct": L["to_reversal_pct"]})
    return out


def compute(state, site, today):
    d0 = date.fromisoformat(state["alt_d0"])
    cleared = date.fromisoformat(state["alt_cleared"])
    return {
        "leg": leg_facts(site, today),
        "alt_leg": alt_leg_facts(site),
        "alt": {"day": (today - d0).days, "d0": f"{d0:%m-%d}", "d0_close": state["alt_d0_close"],
                "cleared": f"{cleared:%m-%d}", "top3": state["alt_top3"], "top3_en": state["alt_top3_en"]},
    }


def main(runtime="runtime", fetch=fetch_leg):
    target = Path(runtime) / "poster_facts.json"
    target.parent.mkdir(parents=True, exist_ok=True)
    try:
        state = json.loads(STATE.read_text())
        facts = {"ok": True, **compute(state, fetch(), datetime.now(BEIJING).date())}
        lg = facts["leg"]
        print(f"::notice title=海报数据::BTC {'涨腿' if lg['dir'] == 'up' else '跌腿'}第{lg['day']}天（网站数据截至 {lg['asof']}），山寨窗口D0+{facts['alt']['day']}", flush=True)
    except Exception as exc:  # noqa: BLE001 - never block the snapshot upload
        facts = {"ok": False, "error": str(exc)[:300]}
        print("::warning title=海报数据未生成::" + str(exc)[:300].replace("%", "%25").replace("\n", " "), flush=True)
    target.write_text(json.dumps(facts, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    sys.exit(main(*(sys.argv[1:2])))
